// BFS shortest path finder
export function getShortestPath(start: string, target: string): string[] | null {
  if (start === target) return [start];
  
  const queue: string[][] = [[start]];
  const visited = new Set<string>([start]);

  while (queue.length > 0) {
    const currentPath = queue.shift()!;
    const lastNode = currentPath[currentPath.length - 1];

    if (lastNode === target) {
      return currentPath;
    }

    const neighbors = PROVINCE_ADJACENCY[lastNode] || [];
    for (const neighbor of neighbors) {
      if (!visited.has(neighbor)) {
        visited.add(neighbor);
        queue.push([...currentPath, neighbor]);
      }
    }
  }

  return null;
}

// Check if two cities share a land border
export function areNeighbors(cityA: string, cityB: string): boolean {
  const list = PROVINCE_ADJACENCY[cityA];
  if (!list) return false;
  return list.includes(cityB);
}

// Haversine distance calculator between 2 cities in km
export function calculateCityDistance(cityA: string, cityB: string): number {
  const cA = CITY_COORDINATES[cityA];
  const cB = CITY_COORDINATES[cityB];
  if (!cA || !cB) return 0;

  const [lat1, lon1] = cA;
  const [lat2, lon2] = cB;
  const R = 6371; // Earth radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c);
}

// Total route distance in km
export function calculateTotalPathDistance(path: string[]): number {
  let total = 0;
  for (let i = 0; i < path.length - 1; i++) {
    total += calculateCityDistance(path[i], path[i + 1]);
  }
  return total;
}

